import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Users/404/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('console', (msg) => { if (msg.type() === 'error') errors.push(`console: ${msg.text()}`); });
page.on('pageerror', (err) => errors.push(`pageerror: ${err.message}`));
await page.goto('http://127.0.0.1:5173', { waitUntil: 'networkidle' });
await page.locator('.tree-connection', { hasText: '示例数据库 · 电商' }).click();
await page.waitForSelector('.tree-db', { timeout: 15000 });
await page.locator('.tree-db', { hasText: 'main' }).first().click();
await page.waitForSelector('.tree-object', { timeout: 15000 });
const smoke = page.locator('.tree-object', { hasText: 'ui_smoke_test' }).first();
console.log('smoke count', await smoke.count());
await smoke.click();
await page.waitForSelector('.table-view', { timeout: 15000 });
await page.waitForTimeout(600);
console.log('tabs:', await page.locator('.object-tab').allInnerTexts());
console.log('design buttons before:', await page.getByRole('button', { name: '设计' }).count());
await page.getByRole('button', { name: '设计' }).click();
await page.waitForTimeout(800);
console.log('design view count:', await page.locator('.design-view').count());
console.log('add column count:', await page.getByRole('button', { name: '添加列' }).count());
console.log('object content snippet:', (await page.locator('.object-content').innerText()).slice(0, 400));
await page.screenshot({ path: '../screenshots/debug-design.png' });
console.log('errors:', JSON.stringify(errors, null, 2));
await browser.close();
